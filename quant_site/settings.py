def _load_local_env(path):
    """Load simple KEY=VALUE settings for local development only.

    Process environment variables always win.  Production deployments should
    inject secrets through the process environment and need not ship `.env`.
    This keeps the project dependency-free while still making local setup
    reproducible.
    """
    if not path.is_file():
        return
    for raw_line in path.read_text(encoding="utf-8").splitlines():
        line = raw_line.strip()
        if not line or line.startswith("#") or "=" not in line:
            continue
        name, value = line.split("=", 1)
        name = name.strip()
        if not name or not name.replace("_", "").isalnum() or name[0].isdigit():
            continue
        value = value.strip()
        if len(value) >= 2 and value[0] == value[-1] and value[0] in {"'", '"'}:
            value = value[1:-1]
        os.environ.setdefault(name, value)


_load_local_env(BASE_DIR / ".env")


